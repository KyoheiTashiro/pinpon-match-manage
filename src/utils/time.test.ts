import { formatDate } from "@/utils/time";
import { describe, it, expect } from "vitest";

describe("formatDate", () => {
  // ---------------------------------------------------------------------------
  // 正常系: 固定日付で JST フォーマットを検証
  // ---------------------------------------------------------------------------

  it("ISO 文字列を '年月日' 形式（JST）に変換する", () => {
    // 2026-01-15T00:00:00+09:00 → 2026年1月15日
    expect(formatDate("2026-01-15T00:00:00+09:00")).toBe("2026年1月15日");
  });

  it("月・日の先頭ゼロを除去する（例: 01月 → 1月）", () => {
    expect(formatDate("2026-03-05T00:00:00+09:00")).toBe("2026年3月5日");
  });

  it("UTC 時刻を JST に変換して表示する", () => {
    // 2026-06-19T00:00:00Z = JST 2026-06-19T09:00:00+09:00 → 2026年6月19日
    expect(formatDate("2026-06-19T00:00:00Z")).toBe("2026年6月19日");
  });

  it("UTC 深夜の日付は JST では翌日になる", () => {
    // 2026-01-31T15:30:00Z = JST 2026-02-01T00:30:00+09:00 → 2026年2月1日
    expect(formatDate("2026-01-31T15:30:00Z")).toBe("2026年2月1日");
  });

  it("年末最終日 (12月31日) を正しくフォーマットする", () => {
    expect(formatDate("2025-12-31T00:00:00+09:00")).toBe("2025年12月31日");
  });

  it("年始 (1月1日) を正しくフォーマットする", () => {
    expect(formatDate("2025-01-01T00:00:00+09:00")).toBe("2025年1月1日");
  });

  // ---------------------------------------------------------------------------
  // 異常系: 無効な入力
  // ---------------------------------------------------------------------------

  it("空文字列は '' を返す", () => {
    expect(formatDate("")).toBe("");
  });

  it("不正な日付文字列は '' を返す", () => {
    expect(formatDate("not-a-date")).toBe("");
  });

  it("アルファベット混じりの不正文字列は '' を返す", () => {
    expect(formatDate("abc-xyz")).toBe("");
  });
});
